public void listarProductosInventario() {
    List<Producto> lista = pDao.listar();
    modeloInventario = (DefaultTableModel) jTableInv.getModel();
    modeloInventario.setRowCount(0);
    Object[] ob = new Object[8];
    for (int i = 0; i < lista.size(); i++) {
        ob[0] = lista.get(i).getIdProducto();
        ob[1] = lista.get(i).getNomProd();
        ob[2] = lista.get(i).getIdCategoria(); 
        ob[3] = lista.get(i).getPrecio();
        ob[4] = lista.get(i).getIdProveedor();
        ob[5] = lista.get(i).getStock();
        ob[6] = lista.get(i).getStockMin();
        ob[7] = lista.get(i).getCodigoBarras();
        modeloInventario.addRow(ob);
    }
}
private void cargarTablaConFiltros(String proveedor, String categoria, String estado) {

    List<Producto> lista = pDao.buscarPorFiltros(proveedor, categoria, estado);

    modeloInventario = (DefaultTableModel) jTableInv.getModel();
    modeloInventario.setRowCount(0);

    Object[] ob = new Object[10];

    for (Producto p : lista) {
        ob[0] = p.getIdProducto();
        ob[1] = p.getNomProd();
        ob[2] = p.getCategoria();
        ob[3] = p.getPrecio();
        ob[4] = p.getPrecioMayoreo();
        ob[5] = p.getProveedor();
        ob[6] = p.getStock();
        ob[7] = p.getStockMin();
        ob[8] = p.getCodigoBarras();
        ob[9] = p.getEstado();

        modeloInventario.addRow(ob);
    }
}
private void llenarCombos() {
    CategoriaDAO catDao = new CategoriaDAO();
    ProveedorDAO provDao = new ProveedorDAO();

    try {
        List<Categoria> listaCat = catDao.listar();
        InventarioCBCat.removeAllItems();
        InventarioCBCat.addItem("Seleccionar Categoría");
        for (Categoria cat : listaCat) {
            InventarioCBCat.addItem(cat.getNombreCat());
        }
    } catch (Exception e) {
        System.out.println("Error al cargar combos de categorías: " + e.getMessage());
    }

    try {
        List<Proveedor> listaProv = provDao.listar();
        InventarioCBProv.removeAllItems();
        InventarioCBProv.addItem("Seleccionar Proveedor");
        for (Proveedor prov : listaProv) {
            InventarioCBProv.addItem(prov.getNomProv());
        }
    } catch (Exception e) {
        System.out.println("Error al cargar combos de proveedores: " + e.getMessage());
    }

    InventarioCBEstado.removeAllItems();
    InventarioCBEstado.addItem("Seleccionar Estado");
    InventarioCBEstado.addItem("Activo");
    InventarioCBEstado.addItem("Inactivo");
    InventarioCBEstado.addItem("Agotado");
}

