    private void btnCerrarTurnoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCerrarTurnoActionPerformed
    String totalVentas = lblVentasRealizadas.getText();
    String totalDinero = lblIngresosTotales.getText();
    
    int respuesta = JOptionPane.showConfirmDialog(null, 
        "RESUMEN DE CIERRE:\n" +
        "Ventas: " + totalVentas + "\n" +
        "Total Caja: $" + totalDinero + "\n\n" +
        "¿Deseas exportar el reporte completo antes de cerrar?", 
        "Confirmar Cierre de Turno", JOptionPane.YES_NO_CANCEL_OPTION);
        
    if (respuesta == JOptionPane.YES_OPTION) {
        Reportes r = new Reportes();
        r.exportarReporteCompleto(jTableStockBajo, jTableVentas);
        limpiarPantallaCierre(); 
    } else if (respuesta == JOptionPane.NO_OPTION) {
        limpiarPantallaCierre();
    }
}

private void limpiarPantallaCierre() {
    lblVentasRealizadas.setText("0");
    lblIngresosTotales.setText("0.00");
    ((DefaultTableModel)jTableVentas.getModel()).setRowCount(0);
    JOptionPane.showMessageDialog(null, "Turno cerrado y caja reiniciada.");
    }//GEN-LAST:event_btnCerrarTurnoActionPerformed

    private void btnBuscarReporteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarReporteActionPerformed
    if (jDateChooser1.getDate() != null && jDateChooser2.getDate() != null) {
        
        java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("yyyy-MM-dd");
        String fechaI = sdf.format(jDateChooser1.getDate());
        String fechaF = sdf.format(jDateChooser2.getDate());

        double[] datos = VDao.obtenerResumenVentas(fechaI, fechaF);
        
        lblVentasRealizadas.setText(String.valueOf((int)datos[0])); 
        lblIngresosTotales.setText("$ " + String.valueOf(datos[1]));

        List<Venta> lista = VDao.filtrarVentasPorFecha(fechaI, fechaF);
        
    } else {
        JOptionPane.showMessageDialog(null, "Por favor, selecciona un rango de fechas.");
    }
    }//GEN-LAST:event_btnBuscarReporteActionPerformed

    private void btnExportarStockBajoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExportarStockBajoActionPerformed
    Reportes reportes = new Reportes();
    
    if (jTableStockBajo.getRowCount() > 0) {
        reportes.exportarStockBajo(jTableStockBajo);
    } else {
        JOptionPane.showMessageDialog(null, "No hay productos con stock bajo para exportar.");
    }
    }//GEN-LAST:event_btnExportarStockBajoActionPerformed

    private void BTNuevoTurnoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTNuevoTurnoActionPerformed
    int confirmar = JOptionPane.showConfirmDialog(null, "¿Deseas abrir un nuevo turno?"
            + " Se limpiarán los datos actuales.");
    
    if (confirmar == JOptionPane.YES_OPTION) {
        lblVentasRealizadas.setText("0");
        lblIngresosTotales.setText("0.00");

        DefaultTableModel modelo = (DefaultTableModel) jTableVentas.getModel();
        modelo.setRowCount(0);
        
        JOptionPane.showMessageDialog(null, "Turno abierto. Los contadores están en cero.");
    }
    }//GEN-LAST:event_BTNuevoTurnoActionPerformed


