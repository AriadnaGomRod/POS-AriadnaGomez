    public void actualizarContadores(double montoNuevo) {
        try {
            int ventasActuales = Integer.parseInt(lblVentasRealizadas.getText());
            lblVentasRealizadas.setText(String.valueOf(ventasActuales + 1));

            double ingresosActuales = Double.parseDouble(lblIngresosTotales.getText());
            double nuevoTotal = ingresosActuales + montoNuevo;
            lblIngresosTotales.setText(String.format("%.2f", nuevoTotal));
        } catch (NumberFormatException e) {
            System.out.println("Error al actualizar: " + e.getMessage());
        }
    }

